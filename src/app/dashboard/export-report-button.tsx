'use client';

import { Button } from '@/components/ui/button';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

interface AuditEvent {
  id: string;
  tenant_id: string;
  agent_id: string;
  session_id: string;
  sequence: number;
  tool_name: string;
  input_hash?: string | null;
  output_hash?: string | null;
  error_code?: string | null;
  human_override: boolean;
  created_at: string;
}

interface ExportReportButtonProps {
  records: AuditEvent[];
}

const formatTime = (isoString: string): string => {
  return new Date(isoString).toLocaleString('en-US', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });
};

export function ExportReportButton({ records }: ExportReportButtonProps) {
  const downloadJSONL = () => {
    window.location.href = '/api/report/jsonl';
  };

  const downloadPDF = () => {
    if (records.length === 0) {
      alert('No data to export');
      return;
    }

    const doc = new jsPDF('landscape');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(16);
    doc.text('AgentTrace Audit Report', doc.internal.pageSize.getWidth() / 2, 15, { align: 'center' });

    const headers = [
      'Event ID',
      'Timestamp',
      'Agent ID',
      'Tool Name',
      'Sequence',
      'Status',
    ];

    const data = records.map((record) => [
      record.id.substring(0, 8) + '...',
      formatTime(record.created_at),
      record.agent_id,
      record.tool_name,
      record.sequence.toString(),
      record.human_override ? 'Human Override' : 'Normal',
    ]);

    autoTable(doc, {
      head: [headers],
      body: data,
      startY: 25,
      styles: {
        font: 'helvetica',
        fontSize: 7,
        cellPadding: 2,
      },
      headStyles: {
        fillColor: [242, 242, 242],
        textColor: [0, 0, 0],
        fontStyle: 'bold',
      },
      alternateRowStyles: {
        fillColor: [250, 250, 250],
      },
      margin: { top: 25 },
    });

    const finalY = (doc as any).lastAutoTable.finalY + 10;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(102, 102, 102);
    doc.text(
      'Disclaimer: This report is auto-generated by AgentTrace for compliance audit reference only ' +
      'and does not constitute formal legal advice. Data is sourced from the Supabase audit_events table. ' +
      'All records are protected by a tamper-evident hash chain; any tampering is detectable.',
      doc.internal.pageSize.getWidth() / 2,
      finalY,
      { align: 'center' }
    );

    doc.save('audit-report.pdf');
  };

  return (
    <div className="flex items-center gap-2">
      <Button variant="outline" size="sm" onClick={downloadJSONL}>
        Export JSONL
      </Button>
      <Button variant="outline" size="sm" onClick={downloadPDF}>
        Export PDF
      </Button>
    </div>
  );
}