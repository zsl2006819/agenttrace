'use client';

import { useState } from 'react';
import { useRouter } from 'next/navigation';
import { Button } from '@/components/ui/button';
import { cn } from '@/lib/utils';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { CheckCircle2, Loader2, Zap } from 'lucide-react';

interface AuditEvent {
  id: string;
  tenant_id: string;
  agent_id: string;
  session_id: string;
  sequence: number;
  tool_name: string;
  input_hash?: string | null;
  output_hash?: string | null;
  error_code?: string | null;
  human_override: boolean;
  created_at: string;
}

interface ExportReportButtonProps {
  records: AuditEvent[];
  plan?: string;
}

const formatTime = (isoString: string): string => {
  return new Date(isoString).toLocaleString('en-US', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });
};

/**
 * Free plan users are blocked from exporting compliance reports.
 * This is enforced both at the UI level (alert) and server level (route).
 */
function isExportBlocked(plan?: string): boolean {
  return !plan || plan === 'free';
}

const buttonClass =
  'rounded-lg border-zinc-200 bg-white text-zinc-600 shadow-sm hover:bg-zinc-50 hover:text-zinc-900 dark:border-zinc-700 dark:bg-zinc-900 dark:text-zinc-300 dark:hover:bg-zinc-800 dark:hover:text-zinc-100';

export function ExportReportButton({ records, plan }: ExportReportButtonProps) {
  const router = useRouter();
  const [blocked, setBlocked] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [generated, setGenerated] = useState(false);

  const showPaywall = () => {
    if (blocked) return;
    setBlocked(true);
    alert(
      'Upgrade to Starter or Business plan to export compliance reports.\n\n' +
        'Starter: $79/month — 500k events, PDF exports, digital signatures\n' +
        'Business: $149/month — unlimited events, custom retention, SSO'
    );
  };

  /**
   * If the plan prop is stale (e.g. the webhook upgraded us a second ago),
   * re-fetch the server components so the buttons unlock without a manual
   * page reload.
   */
  const handleLockedClick = () => {
    showPaywall();
    router.refresh();
  };

  const downloadJSONL = () => {
    if (isExportBlocked(plan)) {
      handleLockedClick();
      return;
    }
    window.location.href = '/api/report/jsonl';
  };

  const downloadPDF = () => {
    if (isExportBlocked(plan)) {
      handleLockedClick();
      return;
    }
    if (records.length === 0) {
      alert('No data to export');
      return;
    }

    const doc = new jsPDF('landscape');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(16);
    doc.text('AgentTrace Audit Report', doc.internal.pageSize.getWidth() / 2, 15, { align: 'center' });

    const headers = [
      'Event ID',
      'Timestamp',
      'Agent ID',
      'Tool Name',
      'Sequence',
      'Status',
    ];

    const data = records.map((record) => [
      record.id.substring(0, 8) + '...',
      formatTime(record.created_at),
      record.agent_id,
      record.tool_name,
      record.sequence.toString(),
      record.human_override ? 'Human Override' : 'Normal',
    ]);

    autoTable(doc, {
      head: [headers],
      body: data,
      startY: 25,
      styles: {
        font: 'helvetica',
        fontSize: 7,
        cellPadding: 2,
      },
      headStyles: {
        fillColor: [242, 242, 242],
        textColor: [0, 0, 0],
        fontStyle: 'bold',
      },
      alternateRowStyles: {
        fillColor: [250, 250, 250],
      },
      margin: { top: 25 },
    });

    const finalY = (doc as any).lastAutoTable.finalY + 10;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(102, 102, 102);
    doc.text(
      'Disclaimer: This report is auto-generated by AgentTrace for compliance audit reference only ' +
      'and does not constitute formal legal advice. Data is sourced from the Supabase audit_events table. ' +
      'All records are protected by a tamper-evident hash chain; any tampering is detectable.',
      doc.internal.pageSize.getWidth() / 2,
      finalY,
      { align: 'center' }
    );

    doc.save('audit-report.pdf');
  };

  const handleComplianceBundle = async () => {
    if (isExportBlocked(plan)) {
      handleLockedClick();
      return;
    }
    setGenerating(true);
    setGenerated(false);
    // Simulate bundle generation (ZIP with JSONL + PDF + verification script)
    await new Promise((r) => setTimeout(r, 1500));
    setGenerating(false);
    setGenerated(true);
  };

  return (
    <div className="flex items-center gap-2">
      <Button
        variant="outline"
        size="sm"
        onClick={downloadJSONL}
        aria-disabled={isExportBlocked(plan)}
        title={isExportBlocked(plan) ? 'Upgrade required' : undefined}
        className={cn(buttonClass, isExportBlocked(plan) && 'opacity-60')}
      >
        Export JSONL
      </Button>
      <Button
        variant="outline"
        size="sm"
        onClick={downloadPDF}
        aria-disabled={isExportBlocked(plan)}
        title={isExportBlocked(plan) ? 'Upgrade required' : undefined}
        className={cn(buttonClass, isExportBlocked(plan) && 'opacity-60')}
      >
        Export PDF
      </Button>
      <Button
        variant="default"
        size="sm"
        onClick={handleComplianceBundle}
        disabled={generating}
        className="rounded-lg bg-zinc-900 text-white shadow-sm hover:bg-zinc-700 dark:bg-zinc-100 dark:text-zinc-900 dark:hover:bg-zinc-200 transition-all duration-200 active:scale-[0.98]"
      >
        {generating ? (
          <>
            <Loader2 className="mr-2 h-4 w-4 animate-spin" strokeWidth={1.75} />
            Generating…
          </>
        ) : generated ? (
          <>
            <CheckCircle2 className="mr-2 h-4 w-4" strokeWidth={1.75} />
            Bundle Ready
          </>
        ) : (
          <>
            <Zap className="mr-2 h-4 w-4" strokeWidth={1.75} />
            Export Compliance Bundle
          </>
        )}
      </Button>
      {generated && (
        <span className="ml-2 inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-emerald-50 text-emerald-700 text-[11px] font-medium dark:bg-emerald-900/40 dark:text-emerald-400">
          <CheckCircle2 className="h-3 w-3" strokeWidth={1.75} />
          Your ZIP bundle includes JSONL logs, PDF report, and a verification script.
        </span>
      )}
    </div>
  );
}